#include <stdio.h>

int main()
{
    // The char data type is used to store
    // a single character.
    //
    // Examples:
    // 'A'
    // 'B'
    // '7'
    // '#'
    //
    // A character is enclosed within
    // single quotation marks.

    char grade = 'A';
    char symbol = '#';

    printf("Grade  : %c\n", grade);
    printf("Symbol : %c\n", symbol);

    return 0;
}